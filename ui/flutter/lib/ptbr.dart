import 'package:flutter/widgets.dart' as w;

final Map<String, String> _cache = <String, String>{};
Map<String, String>? _lower;
List<_Pat>? _compiled;
final RegExp _hasLetter = RegExp(r'[A-Za-z]');

class _Pat {
  _Pat(this.re, this.labels, this.out);
  final RegExp re;
  final List<int> labels;
  final String out;
}

bool ptBrAtivo = true;

/// Traduz [s] para PT-BR quando existir entrada no dicionario; senao devolve [s].
String ptTr(String s) {
  if (!ptBrAtivo || s.isEmpty || !_hasLetter.hasMatch(s)) return s;
  final String? c = _cache[s];
  if (c != null) return c;
  final String r = _translate(s);
  if (_cache.length > 6000) _cache.clear();
  _cache[s] = r;
  return r;
}

String _translate(String s) {
  final String? d = _exact[s];
  if (d != null) return d;
  final String t = s.trim();
  if (t.isEmpty) return s;
  if (t.length != s.length) {
    final int a = s.indexOf(t);
    return s.substring(0, a) + _translate(t) + s.substring(a + t.length);
  }
  final Map<String, String> low = _lower ??= <String, String>{
    for (final MapEntry<String, String> e in _exact.entries)
      e.key.toLowerCase(): e.value,
  };
  final String? l = low[t.toLowerCase()];
  if (l != null) {
    if (t == t.toUpperCase() && t != t.toLowerCase()) return l.toUpperCase();
    final String f = t.substring(0, 1);
    if (f != f.toUpperCase() && l.isNotEmpty) {
      return l.substring(0, 1).toLowerCase() + l.substring(1);
    }
    return l;
  }
  final List<_Pat> pats = _compiled ??= <_Pat>[
    for (final List<Object> p in _patterns)
      _Pat(
        RegExp(p[0] as String, dotAll: true, caseSensitive: false),
        p[1] as List<int>,
        p[2] as String,
      ),
  ];
  for (final _Pat p in pats) {
    final RegExpMatch? m = p.re.firstMatch(t);
    if (m == null) continue;
    String out = p.out;
    for (int i = 0; i < p.labels.length; i++) {
      out = out.replaceAll('{${p.labels[i]}}', ptTr(m.group(i + 1)!));
    }
    if (t == t.toUpperCase() && t != t.toLowerCase()) return out.toUpperCase();
    final String f = t.substring(0, 1);
    if (f != f.toUpperCase() && out.isNotEmpty) {
      return out.substring(0, 1).toLowerCase() + out.substring(1);
    }
    return out;
  }
  return s;
}

w.InlineSpan _trSpan(w.InlineSpan span) {
  if (!ptBrAtivo) return span;
  if (span is w.TextSpan) {
    final String? raw = span.text;
    final List<w.InlineSpan>? kids = span.children;
    return w.TextSpan(
      text: raw != null ? ptTr(raw) : null,
      children: kids?.map(_trSpan).toList(growable: false),
      style: span.style,
      recognizer: span.recognizer,
      mouseCursor: span.mouseCursor,
      onEnter: span.onEnter,
      onExit: span.onExit,
      semanticsLabel: span.semanticsLabel != null ? ptTr(span.semanticsLabel!) : null,
      locale: span.locale,
      spellOut: span.spellOut,
    );
  }
  return span;
}

/// Substitui o Text do Flutter: traduz o texto antes de desenhar.
class Text extends w.StatelessWidget {
  const Text(
    this.data, {
    super.key,
    this.style,
    this.strutStyle,
    this.textAlign,
    this.textDirection,
    this.locale,
    this.softWrap,
    this.overflow,
    this.textScaler,
    this.maxLines,
    this.semanticsLabel,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.selectionColor,
  }) : textSpan = null;

  const Text.rich(
    w.InlineSpan this.textSpan, {
    super.key,
    this.style,
    this.strutStyle,
    this.textAlign,
    this.textDirection,
    this.locale,
    this.softWrap,
    this.overflow,
    this.textScaler,
    this.maxLines,
    this.semanticsLabel,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.selectionColor,
  }) : data = null;

  final String? data;
  final w.InlineSpan? textSpan;
  final w.TextStyle? style;
  final w.StrutStyle? strutStyle;
  final w.TextAlign? textAlign;
  final w.TextDirection? textDirection;
  final w.Locale? locale;
  final bool? softWrap;
  final w.TextOverflow? overflow;
  final w.TextScaler? textScaler;
  final int? maxLines;
  final String? semanticsLabel;
  final w.TextWidthBasis? textWidthBasis;
  final w.TextHeightBehavior? textHeightBehavior;
  final w.Color? selectionColor;

  @override
  w.Widget build(w.BuildContext context) {
    if (textSpan != null) {
      return w.Text.rich(
        _trSpan(textSpan!),
        style: style,
        strutStyle: strutStyle,
        textAlign: textAlign,
        textDirection: textDirection,
        locale: locale,
        softWrap: softWrap,
        overflow: overflow,
        textScaler: textScaler,
        maxLines: maxLines,
        semanticsLabel: semanticsLabel != null ? ptTr(semanticsLabel!) : null,
        textWidthBasis: textWidthBasis,
        textHeightBehavior: textHeightBehavior,
        selectionColor: selectionColor,
      );
    }
    return w.Text(
      ptTr(data!),
      style: style,
      strutStyle: strutStyle,
      textAlign: textAlign,
      textDirection: textDirection,
      locale: locale,
      softWrap: softWrap,
      overflow: overflow,
      textScaler: textScaler,
      maxLines: maxLines,
      semanticsLabel: semanticsLabel != null ? ptTr(semanticsLabel!) : null,
      textWidthBasis: textWidthBasis,
      textHeightBehavior: textHeightBehavior,
      selectionColor: selectionColor,
    );
  }
}

